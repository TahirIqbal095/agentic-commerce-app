import { AnimatePresence, motion, useReducedMotion } from "motion/react";

import { cn } from "@/lib/utils";
import { isCustomerActionEntry } from "@/modules/agent/customer-action-entry";
import type { CartView } from "@/modules/cart/cart";
import { isCheckoutReadinessOutdated } from "@/modules/cart/checkout-readiness";
import type { CatalogProduct } from "@/modules/catalog/catalog";
import { AgentMessage } from "./agent-message";
import { AgentProgress } from "./agent-progress";
import { CartPanel, type CartControls } from "./cart-panel";
import { CheckoutReadinessCard } from "./checkout-readiness-card";
import { CustomerMessage } from "./customer-message";
import { IntentSummary } from "./intent-summary";
import { RecommendationCarousel } from "./recommendation-carousel";
import type { CartFeedback, TranscriptEntry } from "./types";

const CHECKOUT_READINESS_PROVENANCE =
  "Generated by the Review for checkout control";

/**
 * A readiness card offers its correction controls only while the current Cart
 * is known. Until the authoritative Cart has been read, the Storefront cannot
 * tell whether the card is still current, so it withholds the controls rather
 * than inviting a correction to a Cart it may be describing wrongly.
 */

export function ResultArea({
  isLoading,
  onViewProduct,
  onAddProduct,
  addingProductIds,
  cartFeedback,
  entries,
  currentCart,
  cartControls,
}: {
  isLoading: boolean;
  onViewProduct: (product: CatalogProduct) => void;
  onAddProduct: (product: CatalogProduct) => void;
  addingProductIds: ReadonlySet<string>;
  cartFeedback: Record<string, CartFeedback>;
  entries: TranscriptEntry[];
  currentCart: CartView | null;
  cartControls: CartControls;
}) {
  const reduceMotion = useReducedMotion();

  return (
    <section
      aria-live="polite"
      aria-busy={isLoading}
      className="w-full space-y-7"
    >
      {entries.map((entry) => {
        if (isCustomerActionEntry(entry)) {
          return (
            <div key={entry.id} className="space-y-7">
              <CustomerMessage
                message={entry.message}
                provenanceNote={CHECKOUT_READINESS_PROVENANCE}
              />
              <CheckoutReadinessCard
                readiness={entry.readiness}
                isOutdated={isCheckoutReadinessOutdated(
                  entry.readiness,
                  currentCart,
                )}
                controls={currentCart ? cartControls : undefined}
              />
            </div>
          );
        }

        const turn = entry;
        const intent =
          turn.result?.intentBrief?.constraints ?? turn.result?.intent;
        const isPending =
          isLoading && turn.result === null && turn.error === null;
        const isNeedsInput = turn.result?.status === "NEEDS_INPUT";
        const turnCart = turn.result?.cart;
        const inspectedCart =
          turnCart && "items" in turnCart ? turnCart : null;

        return (
          <div key={turn.id} className="space-y-7">
            <CustomerMessage message={turn.customerMessage} />

            <AnimatePresence initial={false}>
              {isPending ? (
                <motion.div
                  key="loading"
                  initial={{ opacity: 0, y: reduceMotion ? 0 : 8 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0 }}
                >
                  <AgentMessage>
                    <AgentProgress />
                  </AgentMessage>
                </motion.div>
              ) : null}

              {turn.error ? (
                <motion.div
                  key="error"
                  initial={{ opacity: 0, y: 8 }}
                  animate={{ opacity: 1, y: 0 }}
                >
                  <AgentMessage>
                    <div className="rounded-2xl border border-red-200 bg-red-50/90 px-5 py-4 text-sm text-red-700">
                      {turn.error}
                    </div>
                  </AgentMessage>
                </motion.div>
              ) : null}

              {turn.result ? (
                <motion.div
                  key="result"
                  initial={{ opacity: 0, y: reduceMotion ? 0 : 10 }}
                  animate={{ opacity: 1, y: 0 }}
                  transition={{ duration: 0.4 }}
                >
                  <AgentMessage>
                    <div className="mb-8 flex flex-col gap-5">
                      <p
                        className={cn(
                          "max-w-3xl text-balance font-medium",
                          isNeedsInput
                            ? "text-base leading-7 sm:text-lg"
                            : "text-2xl leading-snug tracking-[-0.025em] sm:text-3xl",
                        )}
                      >
                        {turn.result.message}
                      </p>
                      {intent && !isNeedsInput ? (
                        <IntentSummary intent={intent} />
                      ) : null}
                    </div>

                    {turn.result.products.length > 0 ? (
                      <RecommendationCarousel
                        products={turn.result.products}
                        onViewProduct={onViewProduct}
                        onAddProduct={onAddProduct}
                        addingProductIds={addingProductIds}
                        cartFeedback={cartFeedback}
                      />
                    ) : null}
                    {inspectedCart ? <CartPanel cart={inspectedCart} /> : null}
                  </AgentMessage>
                </motion.div>
              ) : null}
            </AnimatePresence>
          </div>
        );
      })}
    </section>
  );
}
